CREATE TABLE PESSOA(P_ID INT PRIMARY KEY,
	NOME VARCHAR(40) NOT NULL
);

CREATE TABLE ESTUDANTE(P_ID INT PRIMARY KEY,
	STATUS VARCHAR(10),
	CONSTRAINT ID_ESTUDANTE FOREIGN KEY (P_ID) REFERENCES PESSOA (P_ID)
);

CREATE TABLE DEPARTAMENTO(ID_DEPTO INT PRIMARY KEY,
	NOME_DEPTO VARCHAR(40) NOT NULL,
	P_ID INT
);

CREATE TABLE PROFESSOR(P_ID INT PRIMARY KEY,
	ID_DEPTO INT,
	TITULACAO VARCHAR(10),
	CONSTRAINT ID_PROFESSOR FOREIGN KEY (P_ID) REFERENCES PESSOA (P_ID),
	CONSTRAINT ID_DEPARTAMENTO FOREIGN KEY (ID_DEPTO) REFERENCES DEPARTAMENTO (ID_DEPTO)
);

